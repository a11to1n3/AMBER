"""Run result containers with AgentPy-friendly attribute access.

``Model.run()`` returns a :class:`RunResults` mapping. You can use either::

    results['agents']      # dict-style (stable, existing code)
    results.agents         # attribute-style (AgentPy / notebook friendly)

Both forms return the same objects.

Persistence
-----------
::

    results.save("out/run_001")
    restored = RunResults.load("out/run_001")

Saves use a **versioned manifest** (schema v1). Layout::

    run/
      manifest.json          # logical key → file map + checksums
      frames/
        7d8a....parquet      # generated names only (never user keys)
      json/
        a1b2....json

User-controlled keys are never concatenated into filesystem paths. New
payload files always receive unique names; ``manifest.json`` is committed
last via ``os.replace`` so an interrupted save leaves the previous
manifest readable. Load only trusts files listed in the manifest and
verifies SHA-256 checksums.

``format="parquet"`` is the default; set ``allow_fallback=True`` (default)
to fall back to Arrow IPC then CSV when parquet is unavailable.
Pre-manifest 0.4.x directories still load with a migration warning.
"""

from __future__ import annotations

import hashlib
import json
import os
import secrets
import stat
import warnings
from pathlib import Path
from typing import Any, Dict, List, Literal, Optional, Union

PathLike = Union[str, Path]

SCHEMA_VERSION = 1
_MANIFEST_NAME = "manifest.json"
# Legacy predictable temp name — never written to (symlink-attack surface).
_MANIFEST_TMP_LEGACY = "manifest.json.tmp"
_FRAMES_DIR = "frames"
_JSON_DIR = "json"

FrameFormat = Literal["parquet", "arrow", "csv"]


class RunResultsIOError(OSError):
    """Raised when a run directory is corrupt, incomplete, or unsafe."""


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _new_stem() -> str:
    """Return a unique opaque filename stem (no user-controlled content)."""
    return secrets.token_hex(8)


def _safe_join(root: Path, *parts: str) -> Path:
    """Join ``parts`` under ``root`` and reject any path that escapes.

    All payload paths are generated by this module (never from user keys),
    but we still enforce the boundary so a corrupt manifest cannot escape.
    """
    root_res = root.resolve()
    candidate = root_res.joinpath(*parts).resolve()
    try:
        candidate.relative_to(root_res)
    except ValueError as exc:
        raise RunResultsIOError(
            f"Refusing path that escapes run directory: {candidate}"
        ) from exc
    return candidate


def _is_symlink(path: Path) -> bool:
    try:
        return path.is_symlink() or stat.S_ISLNK(os.lstat(path).st_mode)
    except OSError:
        return False


def _write_bytes_exclusive(path: Path, data: bytes) -> None:
    """Create ``path`` with O_EXCL|O_NOFOLLOW|O_BINARY and write ``data`` (fsynced).

    Refuses to open through a pre-existing path (including a symlink). Random
    opaque names should be used by callers so an attacker cannot plant the
    target path ahead of time.

    ``O_BINARY`` is required on Windows so LF is not expanded to CRLF (which
    would desync the stored SHA-256 checksum from the on-disk bytes).
    """
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    # Windows: without O_BINARY, CRT may translate \\n → \\r\\n on write.
    if hasattr(os, "O_BINARY"):
        flags |= os.O_BINARY
    fd = os.open(str(path), flags, 0o644)
    try:
        # Double-check we own a regular file, not a race-swapped symlink.
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode):
            raise RunResultsIOError(f"Refusing non-regular file: {path}")
        written = 0
        while written < len(data):
            n = os.write(fd, data[written:])
            if n <= 0:
                raise RunResultsIOError(f"Short write to {path}")
            written += n
        os.fsync(fd)
    finally:
        os.close(fd)


def _atomic_commit_manifest(root: Path, manifest: Dict[str, Any]) -> None:
    """Write manifest via exclusive random temp + fsync + os.replace.

    Never uses the predictable name ``manifest.json.tmp`` (symlink TOCTOU).
    """
    root = Path(root)
    final = root / _MANIFEST_NAME
    payload = (json.dumps(manifest, indent=2) + "\n").encode("utf-8")
    # Opaque name under root — not guessable as a plantable symlink target.
    tmp_name = f".manifest-{secrets.token_hex(16)}.tmp"
    tmp_path = root / tmp_name
    try:
        _write_bytes_exclusive(tmp_path, payload)
        # Ensure temp is still a regular file before replace.
        st = os.lstat(tmp_path)
        if not stat.S_ISREG(st.st_mode):
            raise RunResultsIOError(
                f"Manifest temp is not a regular file: {tmp_path}"
            )
        # os.replace replaces a symlink *inode* at final (does not follow it),
        # so a planted symlink at manifest.json cannot redirect the write.
        os.replace(str(tmp_path), str(final))
        # Best-effort directory fsync so the rename is durable.
        try:
            dir_fd = os.open(str(root), os.O_RDONLY)
            try:
                os.fsync(dir_fd)
            finally:
                os.close(dir_fd)
        except OSError:
            pass
    finally:
        if tmp_path.exists() or _is_symlink(tmp_path):
            try:
                tmp_path.unlink(missing_ok=True)  # type: ignore[call-arg]
            except TypeError:
                # Python < 3.8 missing_ok not available — we require 3.10+.
                try:
                    tmp_path.unlink()
                except FileNotFoundError:
                    pass


def _contract_to_jsonable(value: list) -> List[Dict[str, Any]]:
    """Serialize full contract certificates (not just violation counts)."""
    out: List[Dict[str, Any]] = []
    for cert in value:
        if isinstance(cert, dict):
            out.append(cert)
            continue
        violations = []
        for v in getattr(cert, "violations", []) or []:
            if isinstance(v, dict):
                violations.append(v)
                continue
            violations.append(
                {
                    "kind": getattr(v, "kind", None),
                    "detail": getattr(v, "detail", None),
                    "severity": getattr(v, "severity", None),
                    "columns": list(getattr(v, "columns", []) or []),
                    "ids": [ _jsonable_id(i) for i in (getattr(v, "ids", []) or []) ],
                }
            )
        out.append(
            {
                "step": getattr(cert, "step", None),
                "ok": getattr(cert, "ok", None),
                "clean": getattr(cert, "clean", None),
                "violations": violations,
            }
        )
    return out


def _jsonable_id(value: Any) -> Any:
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    return str(value)


def _write_frame(
    df: Any,
    path: Path,
    *,
    format: FrameFormat = "parquet",
    allow_fallback: bool = True,
) -> str:
    """Write a Polars frame; return the format actually used.

    Parameters
    ----------
    format:
        Preferred format (``'parquet'`` by default).
    allow_fallback:
        When True, try Arrow IPC then CSV if the preferred format fails.
        When False, re-raise the first write error.
    """
    writers = {
        "parquet": ("parquet", lambda p: df.write_parquet(p)),
        "arrow": ("arrow", lambda p: df.write_ipc(p)),
        "csv": ("csv", lambda p: df.write_csv(p)),
    }
    order: List[FrameFormat]
    if format == "parquet":
        order = ["parquet", "arrow", "csv"] if allow_fallback else ["parquet"]
    elif format == "arrow":
        order = ["arrow", "csv"] if allow_fallback else ["arrow"]
    elif format == "csv":
        order = ["csv"]
    else:
        raise ValueError(f"Unsupported frame format: {format!r}")

    last_err: Optional[BaseException] = None
    for name in order:
        ext = {"parquet": ".parquet", "arrow": ".arrow", "csv": ".csv"}[name]
        target = path.with_suffix(ext)
        try:
            writers[name][1](target)
            return name
        except Exception as exc:
            last_err = exc
            if target.exists():
                try:
                    target.unlink()
                except OSError:
                    pass
            if not allow_fallback:
                raise
    raise RunResultsIOError(
        f"Failed to write frame to {path} (format={format!r}, "
        f"allow_fallback={allow_fallback})"
    ) from last_err


def _read_frame(path: Path, fmt: str) -> Any:
    import polars as pl

    if fmt == "parquet" or path.suffix == ".parquet":
        return pl.read_parquet(path)
    if fmt == "arrow" or path.suffix == ".arrow":
        return pl.read_ipc(path)
    if fmt == "csv" or path.suffix == ".csv":
        return pl.read_csv(path)
    raise RunResultsIOError(f"Unknown frame format {fmt!r} for {path}")


def _is_legacy_layout(root: Path) -> bool:
    """Detect pre-manifest 0.4.x run directories."""
    if (root / _MANIFEST_NAME).is_file():
        return False
    if (root / "info.json").is_file():
        return True
    if any(root.glob("*.parquet")) or any(root.glob("*.arrow")) or any(root.glob("*.csv")):
        return True
    if (root / "extra.json").is_file() or (root / "contract_summary.json").is_file():
        return True
    return False


class RunResults(dict):
    """Dict of run artifacts (``info``, ``agents``, ``model``, …) with attr access.

    Subclasses :class:`dict`, so ``results['agents']``, ``'model' in results``,
    and ``json``/``**results`` keep working. Attribute access is sugar for the
    same keys (inspired by AgentPy's ``DataDict``).
    """

    def __getattr__(self, name: str) -> Any:
        try:
            return self[name]
        except KeyError as exc:
            raise AttributeError(
                f"{type(self).__name__!r} has no key {name!r}; "
                f"available: {sorted(self)}"
            ) from exc

    def __setattr__(self, name: str, value: Any) -> None:
        # Keep normal dict keys as mapping items, not instance attrs.
        self[name] = value

    def __delattr__(self, name: str) -> None:
        try:
            del self[name]
        except KeyError as exc:
            raise AttributeError(name) from exc

    def __repr__(self) -> str:
        keys = ", ".join(sorted(self))
        return f"<RunResults keys=[{keys}]>"

    # --- AgentPy DataDict-ish helpers ---------------------------------------

    def keys_overview(self) -> Dict[str, str]:
        """Return a short map of key → type summary (notebook / debugging)."""
        out: Dict[str, str] = {}
        for k, v in self.items():
            if hasattr(v, "shape") and hasattr(v, "columns"):
                out[k] = f"DataFrame shape={getattr(v, 'shape', '?')} cols={list(v.columns)}"
            elif isinstance(v, dict):
                out[k] = f"dict keys={sorted(v)}"
            elif isinstance(v, list):
                out[k] = f"list len={len(v)}"
            else:
                out[k] = type(v).__name__
        return out

    def model_frame(self):
        """Return the model-level Polars frame (``results['model']``)."""
        return self["model"]

    def agents_frame(self):
        """Return the end-of-run agents Polars frame (``results['agents']``)."""
        return self["agents"]

    def save(
        self,
        path: PathLike,
        *,
        format: FrameFormat = "parquet",
        allow_fallback: bool = True,
    ) -> Path:
        """Persist this run to a directory using a versioned manifest.

        Layout::

            path/
              manifest.json
              frames/<opaque>.parquet|.arrow|.csv
              json/<opaque>.json

        Parameters
        ----------
        path:
            Destination directory (created if missing).
        format:
            Preferred DataFrame format (default ``'parquet'``).
        allow_fallback:
            If True, fall back to Arrow IPC then CSV when the preferred
            format cannot be written. If False, raise on first write failure.

        Notes
        -----
        * Logical keys are stored only in the manifest — never in file paths.
        * Payload files always receive unique generated names.
        * ``manifest.json`` is written to a temp file then committed with
          :func:`os.replace`, so a crash mid-save leaves any previous
          manifest intact and loadable.
        * The current mapping is saved in full; keys removed from this
          object do not reappear on load even if orphaned files remain.

        Returns
        -------
        Path
            The directory path.
        """
        import polars as pl

        root = Path(path)
        root.mkdir(parents=True, exist_ok=True)
        frames_dir = root / _FRAMES_DIR
        json_dir = root / _JSON_DIR
        frames_dir.mkdir(exist_ok=True)
        json_dir.mkdir(exist_ok=True)

        entries: Dict[str, Dict[str, Any]] = {}

        for key, value in self.items():
            # Keys are logical only — never used as path components.
            if not isinstance(key, str):
                raise TypeError(
                    f"RunResults keys must be str for persistence, got {type(key)!r}"
                )

            if isinstance(value, pl.DataFrame):
                stem = _new_stem()
                # Write under frames/; suffix chosen by writer.
                target = _safe_join(root, _FRAMES_DIR, stem)
                used = _write_frame(
                    value,
                    target,
                    format=format,
                    allow_fallback=allow_fallback,
                )
                ext = {"parquet": ".parquet", "arrow": ".arrow", "csv": ".csv"}[used]
                rel = f"{_FRAMES_DIR}/{stem}{ext}"
                file_path = _safe_join(root, _FRAMES_DIR, f"{stem}{ext}")
                entries[key] = {
                    "kind": "dataframe",
                    "format": used,
                    "file": rel,
                    "sha256": _sha256_file(file_path),
                }
                continue

            if key == "contract" and isinstance(value, list):
                payload = _contract_to_jsonable(value)
                stem = _new_stem()
                rel = f"{_JSON_DIR}/{stem}.json"
                file_path = _safe_join(root, _JSON_DIR, f"{stem}.json")
                raw = (json.dumps(payload, default=str, indent=2) + "\n").encode("utf-8")
                _write_bytes_exclusive(file_path, raw)
                entries[key] = {
                    "kind": "contract",
                    "format": "json",
                    "file": rel,
                    "sha256": _sha256_bytes(raw),
                }
                continue

            # JSON-serializable scalar / mapping / list values
            try:
                raw = (json.dumps(value, default=str, indent=2) + "\n").encode("utf-8")
            except TypeError:
                raw = (
                    json.dumps(repr(value), indent=2) + "\n"
                ).encode("utf-8")
            stem = _new_stem()
            rel = f"{_JSON_DIR}/{stem}.json"
            file_path = _safe_join(root, _JSON_DIR, f"{stem}.json")
            _write_bytes_exclusive(file_path, raw)
            entries[key] = {
                "kind": "json",
                "format": "json",
                "file": rel,
                "sha256": _sha256_bytes(raw),
            }

        manifest = {
            "schema_version": SCHEMA_VERSION,
            "entries": entries,
        }
        # Atomic commit with exclusive random temp (never predictable
        # manifest.json.tmp) so a pre-planted symlink cannot redirect writes.
        _atomic_commit_manifest(root, manifest)
        return root

    @classmethod
    def load(cls, path: PathLike) -> "RunResults":
        """Load a directory written by :meth:`save`.

        Manifest (schema v1) directories are verified by checksum. Pre-manifest
        0.4.x layouts are still accepted via a legacy loader that emits a
        :class:`UserWarning` migration notice.
        """
        root = Path(path)
        if not root.is_dir():
            raise FileNotFoundError(f"RunResults directory not found: {root}")

        manifest_path = root / _MANIFEST_NAME
        if manifest_path.is_file():
            return cls._load_manifest(root, manifest_path)
        if _is_legacy_layout(root):
            return cls._load_legacy(root)
        raise RunResultsIOError(
            f"No { _MANIFEST_NAME } and no recognizable legacy layout in {root}"
        )

    @classmethod
    def _load_manifest(cls, root: Path, manifest_path: Path) -> "RunResults":
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise RunResultsIOError(
                f"Corrupt manifest (invalid JSON): {manifest_path}"
            ) from exc

        if not isinstance(manifest, dict):
            raise RunResultsIOError("manifest.json must be a JSON object")

        version = manifest.get("schema_version")
        if version != SCHEMA_VERSION:
            raise RunResultsIOError(
                f"Unsupported manifest schema_version={version!r}; "
                f"expected {SCHEMA_VERSION}"
            )

        entries = manifest.get("entries")
        if not isinstance(entries, dict):
            raise RunResultsIOError("manifest 'entries' must be an object")

        data: Dict[str, Any] = {}
        for key, entry in entries.items():
            if not isinstance(entry, dict):
                raise RunResultsIOError(f"Invalid entry for key {key!r}")
            rel = entry.get("file")
            if not isinstance(rel, str) or not rel:
                raise RunResultsIOError(f"Entry {key!r} missing file path")
            # Reject absolute paths and any escape via resolve boundary check.
            if Path(rel).is_absolute() or ".." in Path(rel).parts:
                raise RunResultsIOError(
                    f"Entry {key!r} has unsafe file path: {rel!r}"
                )
            file_path = _safe_join(root, *Path(rel).parts)
            if not file_path.is_file():
                raise RunResultsIOError(
                    f"Incomplete save: missing file for {key!r}: {rel}"
                )
            expected = entry.get("sha256")
            actual = _sha256_file(file_path)
            if expected is not None and actual != expected:
                raise RunResultsIOError(
                    f"Corrupt file for {key!r}: sha256 mismatch "
                    f"(expected {expected}, got {actual})"
                )

            kind = entry.get("kind")
            fmt = entry.get("format", file_path.suffix.lstrip("."))
            if kind == "dataframe":
                data[key] = _read_frame(file_path, str(fmt))
            else:
                # json / contract / scalar payloads
                try:
                    payload = json.loads(file_path.read_text(encoding="utf-8"))
                except json.JSONDecodeError as exc:
                    raise RunResultsIOError(
                        f"Corrupt JSON payload for {key!r}: {file_path}"
                    ) from exc
                data[key] = payload

        return cls(data)

    @classmethod
    def _load_legacy(cls, root: Path) -> "RunResults":
        """Load a pre-manifest 0.4.x directory (migration path)."""
        import polars as pl

        warnings.warn(
            f"RunResults directory {root} uses the legacy 0.4.x layout "
            f"(no {_MANIFEST_NAME}). Re-save with RunResults.save() to migrate "
            f"to schema_version {SCHEMA_VERSION}.",
            UserWarning,
            stacklevel=3,
        )
        data: Dict[str, Any] = {}
        info_path = root / "info.json"
        if info_path.is_file():
            data["info"] = json.loads(info_path.read_text(encoding="utf-8"))
        for pq in sorted(root.glob("*.parquet")):
            data[pq.stem] = pl.read_parquet(pq)
        for ipc in sorted(root.glob("*.arrow")):
            data.setdefault(ipc.stem, pl.read_ipc(ipc))
        for csv in sorted(root.glob("*.csv")):
            data.setdefault(csv.stem, pl.read_csv(csv))
        extra_path = root / "extra.json"
        if extra_path.is_file():
            extra = json.loads(extra_path.read_text(encoding="utf-8"))
            if isinstance(extra, dict):
                for k, v in extra.items():
                    data.setdefault(k, v)
        contract_path = root / "contract_summary.json"
        if contract_path.is_file() and "contract" not in data:
            data["contract_summary"] = json.loads(
                contract_path.read_text(encoding="utf-8")
            )
        return cls(data)
