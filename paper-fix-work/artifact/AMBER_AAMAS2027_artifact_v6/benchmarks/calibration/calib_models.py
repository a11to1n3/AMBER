# --- summary statistics ----------------------------------------------------

def gini(wealth):
    """Gini coefficient of a non-negative array (0 = equal, ->1 = unequal)."""
    w = np.sort(np.asarray(wealth, dtype=np.float64))
    n = w.size
    s = w.sum()
    if n == 0 or s == 0:
        return 0.0
    cum = np.cumsum(w)
    return float((n + 1 - 2 * cum.sum() / s) / n)


def segregation(x, y, t, G, xp=np):
    """Mean same-type neighbour fraction over occupied-with-neighbours cells.

    Tolerance-independent, so it is a clean observable for calibrating Schelling.
    """
    gt = xp.zeros((G, G), dtype=xp.int8)
    gt[y, x] = t
    ca = _neighbour_counts(gt == 1, xp)
    cb = _neighbour_counts(gt == 2, xp)
    same = xp.where(t == 1, ca[y, x], cb[y, x]).astype(xp.float32)
    total = (ca[y, x] + cb[y, x]).astype(xp.float32)
    occ = total > 0
    if not bool(occ.any()):
        return 0.0
    return float((same[occ] / total[occ]).mean())


# --- calibration models ----------------------------------------------------

class _CalibBase(am.Model):
    """Shared loss bookkeeping: cumulative SSE of 'stat' vs class-level OBSERVED."""

    OBSERVED = None  # np.ndarray of the observed 'stat' trajectory (set per run)

    def _start(self):
        self._sse = 0.0

    def _record(self, stat):
        obs = type(self).OBSERVED
        idx = self.t - 1  # t has already advanced for this step
        if obs is not None and 0 <= idx < len(obs):
            self._sse += float((stat - obs[idx]) ** 2)
        self.record_model("loss", self._sse)
        self.record_model("stat", float(stat))


class SIRCalib(_CalibBase):
    """Well-mixed SIR -- recover (beta, gamma) from the infected-fraction curve."""

    GROUND_TRUTH = {"beta": 0.35, "gamma": 0.08}
    BOUNDS = {"beta": (0.05, 0.60), "gamma": (0.02, 0.25)}
    FIXED = {"n": 3000, "i0_frac": 0.02, "steps": 50}
    params = {"beta": (float, 0.35), "gamma": (float, 0.08),
              "n": (int, 3000), "i0_frac": (float, 0.02), "steps": (int, 50)}

    def setup(self):
        n = self.p.n
        k = max(1, int(self.p.i0_frac * n))
        status = np.zeros(n, dtype=np.int64)
        status[:k] = 1  # I
        self.add_agents(n, status=status)
        self._start()

    def step(self):
        status = self.agents.numpy("status")
        i_frac = float((status == 1).mean())
        p_inf = self.p.beta * i_frac
        r1 = self.rng.random(len(status))
        r2 = self.rng.random(len(status))
        new = status.copy()
        new[(status == 0) & (r1 < p_inf)] = 1
        new[(status == 1) & (r2 < self.p.gamma)] = 2
        self.agents.set(status=new)

    def update(self):
        status = self.agents.numpy("status")
        self._record(float((status == 1).mean()))


class WealthCalib(_CalibBase):
    """Wealth transfer -- recover transfer_prob from the Gini-coefficient curve."""

    GROUND_TRUTH = {"transfer_prob": 0.6}
    BOUNDS = {"transfer_prob": (0.05, 1.0)}
    FIXED = {"n": 2000, "steps": 40, "init_max": 10}
    params = {"transfer_prob": (float, 0.6), "n": (int, 2000),
              "steps": (int, 40), "init_max": (int, 10)}

    def setup(self):
        n = self.p.n
        wealth = self.rng.integers(1, self.p.init_max + 1, size=n).astype(np.float64)
        self.add_agents(n, wealth=wealth)
        self._start()

    def step(self):
        wealth = self.agents.numpy("wealth")
        n = len(wealth)
        active = (wealth > 0) & (self.rng.random(n) < self.p.transfer_prob)
        idx = np.nonzero(active)[0]
        if idx.size:
            recipients = self.rng.integers(0, n, size=idx.size)
            wealth = wealth.copy()
            np.add.at(wealth, idx, -1.0)
            np.add.at(wealth, recipients, 1.0)
            self.agents.set(wealth=wealth)

    def update(self):
        self._record(gini(self.agents.numpy("wealth")))


class SchellingCalib(_CalibBase):
    """Schelling segregation -- recover tolerance from the segregation-index curve."""

    GROUND_TRUTH = {"tolerance": 0.42}
    BOUNDS = {"tolerance": (0.10, 0.70)}
    FIXED = {"n": 2500, "density": 0.85, "fraction_a": 0.5, "steps": 30}
    params = {"tolerance": (float, 0.42), "n": (int, 2500), "density": (float, 0.85),
              "fraction_a": (float, 0.5), "steps": (int, 30)}

    def setup(self):
        self._x, self._y, self._t, self._G = schelling_setup(
            self.p.n, self.p.density, self.p.fraction_a, self.rng, np)
        self._start()

    def step(self):
        self._x, self._y = schelling_step(
            self._x, self._y, self._t, self._G, self.p.tolerance, self.rng, np)

    def update(self):
        self._record(segregation(self._x, self._y, self._t, self._G, np))


# --- observed-data generation ----------------------------------------------

def stat_trajectory(model_class, params, seed):
    """Run one simulation and return its recorded 'stat' trajectory (per step)."""
    m = model_class({**params, "seed": int(seed), "show_progress": False})
    res = m.run()
    return res["model"]["stat"].to_numpy().astype(np.float64)


def make_observed(problem, seeds):
    """Mean 'stat' trajectory at ground truth over the given seeds (the data)."""
    problem.OBSERVED = None  # generation must not compute a loss
    trajs = [stat_trajectory(problem, {**problem.FIXED, **problem.GROUND_TRUTH}, s)
             for s in seeds]
    return np.mean(np.stack(trajs, axis=0), axis=0)


