"""Calibration problems: recover known ground-truth parameters of three AMBER
model families from a synthetic "observed" summary trajectory.

Each problem is an AMBER ``Model`` that records a cumulative ``loss`` metric --
the SSE between its own summary statistic and the observed one (installed on the
class as ``OBSERVED`` before a calibration run). Recording ``loss`` lets *every*
calibration method minimise the same quantity:

  * grid / random / Bayesian go through AMBER's ``objective_function`` (metric
    ``'loss'``);
  * SMAC reads ``model.results['model']['loss']``;
  * the GPU batched ensemble (SIR only -- it has a batched model) computes the
    identical SSE over a ``(B, steps)`` trajectory tensor.

The summary statistic ('stat' column) is recorded every step so the observed
trajectory can be generated by running the model at ground truth.
"""

